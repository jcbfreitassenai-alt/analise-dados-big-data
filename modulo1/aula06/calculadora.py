# CALCULADORA:

def soma_dois_numeros(numero1, numero2):
    '''
    Retorna o somatório de dois números quaisquer.
    '''
    soma = numero1 + numero2
    return soma

def subtrai_dois_numeros(numero1, numero2):
    '''
    Retorna a subtração de dois números quaisquer.
    '''
    subtracao = numero1 - numero2
    return subtracao

def multiplica_dois_numeros(numero1, numero2):
    '''
    Retorna a multiplicação de dois números quaisquer.
    '''
    multiplica = numero1 * numero2
    return multiplica

def divide_dois_numeros(numero1, numero2):
    '''
    Retorna a divisão de dois números quaisquer.
    '''
    divide = numero1 / numero2
    return divide